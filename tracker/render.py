"""Markdown views of the catalog.

README.md is hand-written except for the block between the listing markers,
which is regenerated. CLOSED.md is fully generated. Everything taken from job
sites is escaped, so a posting title cannot inject links, HTML or table breaks.
"""

from __future__ import annotations

import re
from datetime import date
from urllib.parse import quote, urlsplit

from tracker.config import Settings
from tracker.screen import FAMILIES

START_MARKER = "<!-- listings:start -->"
END_MARKER = "<!-- listings:end -->"
CLOSED_LIMIT = 500
APPLY_BUTTON = "assets/apply-button.svg"
PROGRAMS_HEADING = "Company program pages"

# README section order and headings, keyed by the stored `family` value.
SECTIONS: tuple[tuple[str, str], ...] = (
    ("R&D & Biomedical", "Biomedical / R&D"),
    ("Software & IT", "Software / IT"),
    ("Data & AI", "Data / ML / AI"),
    ("Electrical & Firmware", "Electrical / Firmware"),
    ("Mechanical & Robotics", "Mechanical / Robotics"),
    ("Clinical & Regulatory", "Clinical / Regulatory"),
    ("Quality & Manufacturing", "Quality / Manufacturing"),
    ("Other STEM", "Other STEM"),
)
assert {family for family, _ in SECTIONS} == set(FAMILIES), "every family needs a README section"
_MARKDOWN_SPECIAL = re.compile(r"([\\`*_{}\[\]()#+!|~])")


def cell(text: object) -> str:
    value = " ".join(("" if text is None else str(text)).split())
    value = value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return _MARKDOWN_SPECIAL.sub(r"\\\1", value)


def safe_url(url: str) -> str | None:
    parts = urlsplit(url.strip())
    if parts.scheme not in ("http", "https") or not parts.netloc:
        return None
    # Percent-encode anything that could end the Markdown link early.
    return quote(url.strip(), safe=":/?#@!$&'*+,;=%~-._[]")


def link(label: object, url: str) -> str:
    target = safe_url(url)
    return f"[{cell(label)}]({target})" if target else cell(label)


def apply_button(url: str) -> str:
    target = safe_url(url)
    return f"[![Apply]({APPLY_BUTTON})]({target})" if target else "—"


def anchor(heading: str) -> str:
    """The fragment GitHub generates for a Markdown heading."""
    kept = "".join(char for char in heading.lower() if char.isalnum() or char in " -_")
    return kept.replace(" ", "-")


def age(since: str, today: str | None) -> str:
    """How long a listing has been up, relative to the last refresh."""
    if not today:
        return "—"
    days = (date.fromisoformat(today) - date.fromisoformat(since)).days
    if days < 1:
        return "new"
    if days < 14:
        return f"{days}d"
    if days < 60:
        return f"{days // 7}w"
    return f"{days // 30}mo"


def listings_block(listings: list[dict], status: dict, settings: Settings) -> str:
    current = [
        row for row in listings if row["status"] == "open" and row["season"] == settings.season
    ]
    companies = {row["company"] for row in current}
    today = status.get("last_run")
    sections = []
    for family, heading in SECTIONS:
        rows = [row for row in current if row["family"] == family]
        if rows:
            rows.sort(key=lambda row: (row["company"].lower(), row["title"].lower(), row["id"]))
            rows.sort(key=_since, reverse=True)  # stable: ties keep the order above
            sections.append((heading, rows))

    programs = program_pages(current, settings)
    lines = [
        START_MARKER,
        "<!-- Generated by `python -m tracker render`. Edits inside these markers are lost. -->",
        "",
        f"**{len(current)} open {settings.season_label} internships** at "
        f"{len(companies)} of {len(settings.companies)} tracked companies, plus "
        f"{len(programs)} company internship program pages. "
        f"Last refreshed {today or 'never'}.",
        "",
    ]
    if not sections:
        lines += ["_No open listings right now._", ""]
    jumps = [f"[{heading}](#{anchor(heading)}) ({len(rows)})" for heading, rows in sections]
    if programs:
        jumps.append(f"[{PROGRAMS_HEADING}](#{anchor(PROGRAMS_HEADING)}) ({len(programs)})")
    if jumps:
        lines += ["## Browse by role", "", " · ".join(jumps), ""]
    for heading, rows in sections:
        lines += [
            f"## {heading}",
            "",
            "| Company | Role | Location | Apply | Age |",
            "| --- | --- | --- | :---: | ---: |",
        ]
        lines += [
            f"| {cell(row['company'])} | {cell(row['title'])} | "
            f"{cell(row['location']) or '—'} | {apply_button(row['url'])} | "
            f"{age(_since(row), today)} |"
            for row in rows
        ]
        lines.append("")
    lines += _program_section(programs)
    lines += _stats_table(listings, status, settings)
    lines += _company_table(listings, status, settings)
    lines.append(END_MARKER)
    return "\n".join(lines)


def program_pages(current: list[dict], settings: Settings) -> list:
    """Companies with no open postings this season that have a program page."""
    hiring = {row["company"] for row in current}
    return sorted(
        (
            company
            for company in settings.companies
            if company.program and company.name not in hiring
        ),
        key=lambda company: company.name.lower(),
    )


def _program_section(programs: list) -> list[str]:
    if not programs:
        return []
    lines = [
        f"## {PROGRAMS_HEADING}",
        "",
        "These companies have no open postings we can read right now. Their own internship "
        "pages list programs and open roles.",
        "",
        "| Company | Program | Location | Apply | Age |",
        "| --- | --- | --- | :---: | ---: |",
    ]
    lines += [
        f"| {cell(company.name)} | {cell(company.program.label)} | "
        f"{cell(company.program.location) or '—'} | {apply_button(company.program.url)} | — |"
        for company in programs
    ]
    lines.append("")
    return lines


def _stats_table(listings: list[dict], status: dict, settings: Settings) -> list[str]:
    current = [
        row for row in listings if row["status"] == "open" and row["season"] == settings.season
    ]
    closed = [
        row for row in listings if row["status"] == "closed" and row["season"] == settings.season
    ]
    results = status.get("companies", {})
    failed = sorted(name for name, result in results.items() if not result.get("ok"))
    link_only = {company.name for company in settings.companies if company.link_only}
    readable = sum(1 for name in results if name not in link_only)
    return [
        "## Tracker stats",
        "",
        f"**{len(current)}** open listings for `{settings.season}`.",
        "",
        "| Last refresh | Open | Companies hiring | Program pages | Companies read | Failed reads "
        "| Closed |",
        "| --- | ---: | ---: | ---: | ---: | --- | ---: |",
        f"| {status.get('last_run') or '—'} | {len(current)} | "
        f"{len({row['company'] for row in current})} | {len(program_pages(current, settings))} | "
        f"{readable} | {cell(', '.join(failed)) or 'none'} | {len(closed)} |",
        "",
        "Closed listings are in [CLOSED.md](CLOSED.md).",
        "",
    ]


def _company_table(listings: list[dict], status: dict, settings: Settings) -> list[str]:
    results = status.get("companies", {})
    lines = [
        "## Companies",
        "",
        "| Company | Platform | Open | Last read | Fetched |",
        "| --- | --- | --- | --- | ---: |",
    ]
    for company in sorted(settings.companies, key=lambda item: item.name.lower()):
        open_count = sum(
            1
            for row in listings
            if row["company"] == company.name
            and row["status"] == "open"
            and row["season"] == settings.season
        )
        result = results.get(company.name)
        fetched = "—"
        if company.link_only:
            state = "link only"
        elif result is None:
            state = "—"
        else:
            state = "ok" if result.get("ok") else "failed"
            if result.get("fetched") is not None:
                fetched = cell(result["fetched"])
        lines.append(
            f"| {link(company.name, company.careers_url)} | "
            f"{'—' if company.link_only else cell(company.platform)} | "
            f"{open_count} | {state} | {fetched} |"
        )
    lines.append("")
    return lines


def _since(row: dict) -> str:
    return row["posted_on"] or row["first_seen"]


def splice(readme: str, block: str) -> str:
    start = readme.find(START_MARKER)
    end = readme.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise ValueError("README.md is missing the listing markers")
    return readme[:start] + block + readme[end + len(END_MARKER) :]


def closed_page(listings: list[dict]) -> str:
    closed = [row for row in listings if row["status"] == "closed"]
    closed.sort(key=lambda row: (row["company"].lower(), row["title"].lower(), row["id"]))
    closed.sort(key=lambda row: row["closed_on"], reverse=True)
    lines = [
        "# Closed listings",
        "",
        "<!-- Generated by `python -m tracker render`. Do not edit by hand. -->",
        "",
        f"Postings that are no longer open, newest first ({len(closed)} total"
        + (f", showing {CLOSED_LIMIT}" if len(closed) > CLOSED_LIMIT else "")
        + "). `missing` means the posting disappeared from the company's job board; "
        "`manual` means a maintainer closed it; `deadline` means the closing date given when "
        "the listing was submitted passed.",
        "",
    ]
    if not closed:
        return "\n".join([*lines, "_Nothing has closed yet._", ""])
    lines += [
        "| Company | Role | Location | Season | First seen | Closed | Reason |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    lines += [
        f"| {cell(row['company'])} | {cell(row['title'])} | {cell(row['location']) or '—'} | "
        f"{cell(row['season'])} | {row['first_seen']} | {row['closed_on']} | "
        f"{cell(row['close_reason'])} |"
        for row in closed[:CLOSED_LIMIT]
    ]
    lines.append("")
    return "\n".join(lines)
